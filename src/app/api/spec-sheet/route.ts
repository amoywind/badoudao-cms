import { getProduct, getSettings } from '@/lib/db';

/**
 * The specification sheet, as a text file.
 *
 * §5.3-2 asks for a "Download Spec Sheet (.TXT/PDF)" next to the quote
 * button. A plain text file rather than a PDF: the buyer who wants this
 * is usually putting the numbers into a spreadsheet or a comparison
 * table, and a PDF has to be retyped to get into one. Text pastes.
 *
 * It is served as a dynamic route rather than a static file because the
 * sheet is the product's own numbers — the price range, the minimum
 * order, the carton, the specifications — and a static file would have
 * to be regenerated by hand every time a price moved.
 */

export const runtime = 'edge';
export const dynamic = 'force-dynamic';

export async function GET(request) {
  const url = new URL(request.url);
  const slug = url.searchParams.get('slug') || '';
  if (!slug) {
    return new Response('Missing slug', { status: 400 });
  }

  const [product, s] = await Promise.all([
    getProduct(slug, { includeDrafts: false }).catch(() => null),
    getSettings().catch(() => ({} as Record<string, string>))
  ]);

  if (!product) {
    return new Response('Product not found', { status: 404 });
  }

  const moq = product.moq || Number(s.moq) || 300;
  const carton = (() => {
    if (!product.cartonQty || !product.cartonL || !product.cartonW || !product.cartonH) {
      return null;
    }
    const cbm = (product.cartonL * product.cartonW * product.cartonH) / 1_000_000;
    return { ...product, cbm };
  })();

  const rule = '='.repeat(64);
  const lines: string[] = [
    'OEMWALLCLOCKS.COM — SPECIFICATION SHEET',
    rule,
    '',
    `Product      : ${product.name}`,
    `SKU          : ${product.id}`,
    `Category     : ${product.category}`,
    `Lead time    : ${product.leadTime}`,
    '',
    'PRICING (Ex Works, per piece)',
    rule,
    `Range        : USD ${product.priceMin.toFixed(2)} - ${product.priceMax.toFixed(2)}`,
    `MOQ          : ${moq} pcs (mixed colors and specifications allowed)`,
    '',
    'MOVEMENT',
    rule,
    `Type         : ${product.moveLevel || 'Quartz — specify on enquiry'}`,
    '',
    'PACKING & FREIGHT',
    rule
  ];

  if (carton) {
    lines.push(
      `Clocks/carton: ${carton.cartonQty}`,
      `Carton size  : ${carton.cartonL} x ${carton.cartonW} x ${carton.cartonH} cm`,
      `Gross weight : ${carton.cartonGw ?? '—'} kg`,
      `Volume       : ${carton.cbm.toFixed(3)} CBM`,
      `20ft load    : ${Math.floor(28.0 / carton.cbm) * carton.cartonQty} clocks`,
      `40ft HC load : ${Math.floor(67.7 / carton.cbm) * carton.cartonQty} clocks`
    );
  } else {
    lines.push(
      'Carton data  : not on file — the freight estimator on the product page',
      '               starts from a typical packing for this size, and the',
      '               factory confirms the real carton with the quotation.'
    );
  }

  if (product.specs.length) {
    lines.push('', 'DIMENSIONS & SPECIFICATION', rule);
    product.specs.forEach((sp) => {
      lines.push(`${(sp.label + ' ').padEnd(22, '.')} ${sp.value}`);
    });
  }

  if (product.summary) {
    lines.push('', 'SUMMARY', rule, product.summary);
  }

  lines.push(
    '',
    rule,
    'Xiamen Orange Cat Creative Home Decor Co., Ltd.',
    'MOQ 300 pcs · 24h 3D CAD rendering · 1.2m ISTA-1A drop-tested packaging',
    'www.oemwallclocks.com'
  );

  const filename = `spec-${(product.slug || product.id).replace(/[^a-z0-9-]/gi, '-')}.txt`;

  return new Response(lines.join('\n'), {
    headers: {
      'Content-Type': 'text/plain; charset=utf-8',
      'Content-Disposition': `attachment; filename="${filename}"`,
      'Cache-Control': 'no-store'
    }
  });
}
